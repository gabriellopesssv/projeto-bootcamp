-- Criação da tabela de favoritos
CREATE TABLE IF NOT EXISTS favoritos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  criado_em TIMESTAMPTZ DEFAULT NOW(),
  nome_item TEXT NOT NULL,
  pokemon_id BIGINT NOT NULL,
  tipos TEXT,
  sprite TEXT
);

-- Habilitar Row Level Security (RLS)
ALTER TABLE favoritos ENABLE ROW LEVEL SECURITY;

-- Política para permitir leitura (SELECT) para usuários anônimos
CREATE POLICY "Permitir leitura pública"
ON favoritos
FOR SELECT
TO anon
USING (true);

-- Política para permitir inserção (INSERT) para usuários anônimos
CREATE POLICY "Permitir inserção pública"
ON favoritos
FOR INSERT
TO anon
WITH CHECK (true);

-- Política para permitir deleção (DELETE) para usuários anônimos
CREATE POLICY "Permitir deleção pública"
ON favoritos
FOR DELETE
TO anon
USING (true);

-- Criar índice para busca mais rápida por pokemon_id
CREATE INDEX IF NOT EXISTS idx_favoritos_pokemon_id ON favoritos(pokemon_id);

-- Criar índice para ordenação por data
CREATE INDEX IF NOT EXISTS idx_favoritos_criado_em ON favoritos(criado_em DESC);

-- Comentário explicativo
COMMENT ON TABLE favoritos IS 'Tabela para armazenar Pokémon favoritos dos usuários';
COMMENT ON COLUMN favoritos.nome_item IS 'Nome do Pokémon';
COMMENT ON COLUMN favoritos.pokemon_id IS 'ID numérico do Pokémon da PokéAPI';
COMMENT ON COLUMN favoritos.tipos IS 'Tipos do Pokémon (separados por vírgula)';
COMMENT ON COLUMN favoritos.sprite IS 'URL da imagem do Pokémon';
